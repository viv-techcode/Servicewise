"""Feedback-assisted training with a fixed Step 5d holdout and guarded adoption."""
from __future__ import annotations

import argparse
import json
import os
import shutil
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import f1_score, mean_absolute_error

from backend import db
from backend.ml import train_models as training
from backend.ml.fault_text import prepare_classifier_text

ML_DIR = Path(__file__).resolve().parent
DATA_PATH = ML_DIR.parent / 'data' / 'service_records_balanced_3000.csv'
PREDICTIONS_PATH = ML_DIR / 'test_set_predictions.csv'
VERSIONS_DIR = ML_DIR / 'model_versions'
ARTIFACTS = ('problem_classifier.pkl', 'multilabel_classifier.pkl', 'cost_regressor.pkl')


def adoption_decision(current_micro_f1, candidate_micro_f1, current_cost_mae, candidate_cost_mae,
                      micro_tolerance=0.005, cost_degradation=0.05):
    micro_pass = candidate_micro_f1 >= current_micro_f1 - micro_tolerance
    cost_pass = candidate_cost_mae <= current_cost_mae * (1 + cost_degradation)
    return {'micro_f1_pass': micro_pass, 'cost_mae_pass': cost_pass,
            'adopt': micro_pass and cost_pass}


def load_approved_feedback(connection=None):
    owns = connection is None
    conn = connection or db.get_db()
    rows = conn.execute("""SELECT f.*, r.symptoms, r.predicted_category
        FROM feedback f JOIN service_records r ON r.id=f.record_id
        WHERE f.review_status='approved' AND f.corrected_faults_json IS NOT NULL
        ORDER BY f.id""").fetchall()
    if owns: conn.close()
    result = []
    for row in rows:
        try: labels = json.loads(row['corrected_faults_json'])
        except (TypeError, json.JSONDecodeError): continue
        if not isinstance(labels, list) or not labels or any(label not in training.CATEGORIES for label in labels): continue
        try: details = json.loads(row['vehicle_details_json'] or '{}')
        except (TypeError, json.JSONDecodeError): details = {}
        try: per_cost = json.loads(row['actual_fault_costs_json'] or '{}')
        except (TypeError, json.JSONDecodeError): per_cost = {}
        if not per_cost and row['actual_cost'] is not None:
            per_cost = {labels[0]: float(row['actual_cost'])}
        result.append({**details, 'symptoms': row['symptoms'], 'primary_fault': labels[0],
            'problem_category': labels[0], 'simultaneous_faults': ';'.join(labels[1:]) or 'not_recorded',
            'fault_costs': json.dumps(per_cost), 'actual_repair_cost': per_cost.get(labels[0]),
            'total_repair_cost': float(row['actual_cost']) if row['actual_cost'] is not None else sum(per_cost.values()),
            'state': row['state'] or details.get('state') or 'not_recorded',
            'vehicle_age': details.get('vehicle_age', 0), 'km_driven': details.get('km_driven', 0),
            'vehicle_type': details.get('vehicle_type', 'car'), 'vehicle_brand': details.get('vehicle_brand', 'not_recorded'),
            'vehicle_model': details.get('vehicle_model', 'not_recorded'), '_feedback_id': row['id']})
    return result


def _fixed_benchmark(df):
    predictions = pd.read_csv(PREDICTIONS_PATH)
    # Existing row IDs come from the fixed Step 5d test export. The test file
    # is never appended to or regenerated by this workflow.
    test_ids = set(predictions['record_id'].astype(str))
    if 'record_id' not in df:
        df['record_id'] = np.arange(1, len(df) + 1)
    ids = df['record_id'].astype(str)
    test_idx = np.flatnonzero(ids.isin(test_ids).to_numpy())
    if len(test_idx) != len(test_ids):
        # Step 5d predictions retain source record IDs, while the prepared
        # balanced file contains exactly the rows in original file order.
        # The deterministic Step 5d splitter is the authoritative fallback.
        splits, _ = training.group_aware_split(df, seed=training.SPLIT_SEED)
        test_idx = np.asarray(splits['test'], dtype=int)
    if len(test_idx) != len(test_ids):
        raise ValueError('Could not reproduce the fixed Step 5d test benchmark.')
    return predictions, test_idx


def _cost_benchmark(model, df, test_idx):
    x_test, y_test, _ = training.cost_training_data(df, test_idx)
    return float(mean_absolute_error(y_test, model.predict(x_test)))


def compare_models(candidate_classifier, candidate_cost, base_df, feedback_rows):
    _, test_idx = _fixed_benchmark(base_df)
    mlb, y = training.labels_from_frame(base_df)
    classes = list(mlb.classes_)
    thresholds = np.asarray([training_metrics['classifier']['decision_thresholds'][c] for c in classes])
    # The current artifact and candidate are scored over the same immutable rows.
    current_meta = joblib.load(ML_DIR / 'multilabel_classifier.pkl')
    benchmark_text = base_df.iloc[test_idx]['symptoms'].map(prepare_classifier_text)
    current_proba = current_meta['pipeline'].predict_proba(benchmark_text)
    candidate_proba = candidate_classifier.predict_proba(benchmark_text)
    current_pred = training.multilabel_predictions(current_proba, thresholds)
    candidate_pred = training.multilabel_predictions(candidate_proba, thresholds)
    current_f1 = float(f1_score(y[test_idx], current_pred, average='micro', zero_division=0))
    candidate_f1 = float(f1_score(y[test_idx], candidate_pred, average='micro', zero_division=0))
    current_cost = joblib.load(ML_DIR / 'cost_regressor.pkl')
    current_mae = _cost_benchmark(current_cost, base_df, test_idx)
    candidate_mae = _cost_benchmark(candidate_cost, base_df, test_idx)
    gates = adoption_decision(current_f1, candidate_f1, current_mae, candidate_mae)
    return {
        'benchmark': 'fixed Step 5d test_set_predictions.csv record IDs; feedback is excluded',
        'test_rows': len(test_idx),
        'current': {'micro_f1': current_f1, 'per_fault_cost_mae': current_mae},
        'candidate': {'micro_f1': candidate_f1, 'per_fault_cost_mae': candidate_mae},
        'micro_f1_tolerance': 0.005,
        'cost_mae_max_degradation_fraction': 0.05,
        **gates,
    }


def _selected_classifier_pipeline():
    global training_metrics
    training_metrics = json.loads((ML_DIR / 'model_metrics.json').read_text(encoding='utf-8'))
    name = training_metrics['classifier']['selected_model']
    return next(pipeline for candidate_name, pipeline in training.classifier_candidates() if candidate_name == name)


def train_candidate(feedback_rows):
    df = pd.read_csv(DATA_PATH)
    df['problem_category'] = df['primary_fault'].fillna(df['problem_category'])
    df['actual_repair_cost'] = pd.to_numeric(df['actual_repair_cost'], errors='coerce')
    df['total_repair_cost'] = pd.to_numeric(df['total_repair_cost'], errors='coerce')
    df['state'] = df['state'].fillna('not_recorded')
    _, test_idx = _fixed_benchmark(df)
    benchmark_ids = set(df.iloc[test_idx]['record_id'].astype(str))
    if any(str(row.get('record_id', '')) in benchmark_ids for row in feedback_rows):
        raise ValueError('Feedback rows cannot be part of the benchmark.')

    # Use every base row outside the immutable test IDs as the training pool.
    # This preserves the test benchmark and the Step 5d model configuration.
    test_idx_set = set(test_idx.tolist())
    train_idx = np.asarray([i for i in range(len(df)) if i not in test_idx_set], dtype=int)
    train_df = df.iloc[train_idx].copy()
    train_df = pd.concat([train_df, pd.DataFrame(feedback_rows)], ignore_index=True, sort=False)
    _, y_train = training.labels_from_frame(train_df)
    text = train_df['symptoms'].fillna('').map(prepare_classifier_text)
    classifier = _selected_classifier_pipeline()
    classifier.fit(text, y_train)

    # Preserve the current validation-selected thresholds and model settings.
    x_cost, y_cost, _ = training.cost_training_data(df, list(train_idx))
    fdf = pd.DataFrame(feedback_rows)
    feedback_cost_rows = []
    feedback_targets = []
    for _, row in fdf.iterrows():
        for category, amount in training.parse_fault_costs(row).items():
            if category in training.CATEGORIES and pd.notna(pd.to_numeric(amount, errors='coerce')):
                item = row.copy(); item['problem_category'] = category
                feedback_cost_rows.append(item); feedback_targets.append(float(amount))
    if feedback_cost_rows:
        x_cost = pd.concat([x_cost, training.cost_features(pd.DataFrame(feedback_cost_rows))], ignore_index=True)
        y_cost = np.concatenate([y_cost, np.asarray(feedback_targets)])
    chosen_name = json.loads((ML_DIR / 'model_metrics.json').read_text(encoding='utf-8'))['regressor']['selected_model']
    model_by_name = dict(training.cost_candidates())[chosen_name]
    cost_model = training.make_cost_pipeline(model_by_name)
    cost_model.fit(x_cost, y_cost)
    legacy = joblib.load(ML_DIR / 'problem_classifier.pkl')
    return df, classifier, cost_model, legacy


def _save_version(candidate_classifier, candidate_cost, legacy, metrics, adopt):
    VERSIONS_DIR.mkdir(parents=True, exist_ok=True)
    existing = [int(p.name[1:]) for p in VERSIONS_DIR.glob('v[0-9][0-9][0-9]') if p.is_dir()]
    version = f'v{max(existing, default=0) + 1:03d}'
    if not existing:
        # Preserve an exact rollback point for the original Step 5d artifacts.
        baseline = VERSIONS_DIR / 'v000'
        baseline.mkdir(exist_ok=True)
        for artifact in ARTIFACTS:
            shutil.copy2(ML_DIR / artifact, baseline / artifact)
        (baseline / 'metadata.json').write_text(json.dumps({'version': 'v000', 'created_at': training_metrics.get('trained_at'), 'adopted': True, 'baseline': 'Step 5d'}, indent=2), encoding='utf-8')
        version = 'v001'
    folder = VERSIONS_DIR / version
    folder.mkdir()
    current_version = {}
    for artifact in ARTIFACTS:
        shutil.copy2(ML_DIR / artifact, folder / artifact)
    current_version['previous_version'] = _active_version_name()
    classifier_bundle = joblib.load(ML_DIR / 'multilabel_classifier.pkl')
    classifier_bundle['pipeline'] = candidate_classifier
    classifier_bundle['model_version'] = version
    for name, obj in zip(ARTIFACTS, (legacy, classifier_bundle, candidate_cost)):
        joblib.dump(obj, folder / name)
    metadata = {'version': version, 'created_at': datetime.now(timezone.utc).isoformat(),
        'adopted': bool(adopt), 'previous_version': current_version['previous_version'],
        'training_feedback_count': metrics.get('approved_feedback_count', 0), 'metrics': metrics}
    (folder / 'metadata.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    if adopt:
        backups = {}
        replaced = []
        try:
            for artifact in ARTIFACTS:
                target = ML_DIR / artifact
                backup = ML_DIR / (artifact + '.rollback.tmp')
                shutil.copy2(target, backup)
                backups[artifact] = backup
            for artifact in ARTIFACTS:
                target = ML_DIR / artifact
                replaced.append(artifact)
                shutil.copy2(folder / artifact, target)
            temporary_version = ML_DIR / 'active_model_version.json.new'
            temporary_version.write_text(json.dumps({'version': version}, indent=2), encoding='utf-8')
            os.replace(temporary_version, ML_DIR / 'active_model_version.json')
        except Exception:
            for artifact in reversed(replaced):
                shutil.copy2(backups[artifact], ML_DIR / artifact)
            raise
        finally:
            for backup in backups.values():
                backup.unlink(missing_ok=True)
    return version


def _active_version_name():
    path = ML_DIR / 'active_model_version.json'
    return json.loads(path.read_text(encoding='utf-8')).get('version') if path.exists() else 'baseline-step5d'


def rollback(version):
    folder = VERSIONS_DIR / version
    if not folder.is_dir() or not (folder / 'metadata.json').exists():
        raise ValueError(f'Unknown model version: {version}')
    backups = {}
    replaced = []
    try:
        for artifact in ARTIFACTS:
            target = ML_DIR / artifact
            backup = ML_DIR / (artifact + '.rollback.tmp')
            shutil.copy2(target, backup)
            backups[artifact] = backup
        for artifact in ARTIFACTS:
            replaced.append(artifact)
            shutil.copy2(folder / artifact, ML_DIR / artifact)
        temporary_version = ML_DIR / 'active_model_version.json.new'
        temporary_version.write_text(json.dumps({'version': version}, indent=2), encoding='utf-8')
        os.replace(temporary_version, ML_DIR / 'active_model_version.json')
    except Exception:
        for artifact in reversed(replaced):
            shutil.copy2(backups[artifact], ML_DIR / artifact)
        raise
    finally:
        for backup in backups.values(): backup.unlink(missing_ok=True)
    return version


def retrain(dry_run=False):
    global training_metrics
    db.init_db()
    training_metrics = json.loads((ML_DIR / 'model_metrics.json').read_text(encoding='utf-8'))
    feedback_rows = load_approved_feedback()
    base_df, classifier, cost_model, legacy = train_candidate(feedback_rows)
    comparison = compare_models(classifier, cost_model, base_df, feedback_rows)
    adopt = comparison['adopt']
    metrics = {**comparison, 'approved_feedback_count': len(feedback_rows),
        'adoption_decision': 'adopted' if adopt else 'kept_current',
        'decision_reason': 'Both benchmark gates passed.' if adopt else 'Candidate failed at least one fixed-benchmark gate.'}
    if dry_run:
        metrics['dry_run'] = True
        return metrics
    version = _save_version(classifier, cost_model, legacy, metrics, adopt)
    metrics['version'] = version
    log_path = ML_DIR / 'retraining_history.jsonl'
    with log_path.open('a', encoding='utf-8') as handle: handle.write(json.dumps(metrics) + '\n')
    return metrics


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rollback', help='Restore a saved model version, such as v001.')
    parser.add_argument('--dry-run', action='store_true', help='Evaluate a candidate without archiving or adopting it.')
    args = parser.parse_args()
    if args.rollback:
        print(json.dumps({'rolled_back_to': rollback(args.rollback)}))
    else:
        print(json.dumps(retrain(dry_run=args.dry_run), indent=2))


if __name__ == '__main__':
    main()
